"""MCP tools of the ``poster`` area (layered posters, exact text) and ``image_edit`` (non-AI photo edits).

Plain module-level functions plus ``register(server)``. Text on a poster is drawn from the copy deck by ID
(projects) or from a literal marked "casual"; it is never generated by an image model, and every render writes a
text audit proving what was drawn. GL work runs on the one GL thread (``mcp_util.on_gl``).
"""
from __future__ import annotations

from pathlib import Path

from PIL import Image as PILImage

from funkbox.mcp_util import on_gl, png as _png, safe
from funkbox.stills import api, edit as editmod, render, schema, variations


def _out_dir(doc: dict) -> Path:
    if doc.get("project"):
        from funkbox.reel import project as projmod
        return projmod.project_dir(doc["project"]) / "out"
    return api.posters_dir()


# --------------------------------------------------------------------------- #
@safe
def poster_presets() -> str:
    """Canvas presets, layer types, blend modes, filters, effects, export formats and the edit operations."""
    from funkbox.gl.recipe import BLEND_MODES
    rows = ["canvas presets: " + ", ".join(f"{k} {w}x{h}" for k, (w, h) in schema.PRESETS.items())
            + f"  (or width/height, {schema.MIN_SIDE}..{schema.MAX_SIDE}; background may be \"transparent\")",
            "layer types: " + ", ".join(schema.LAYER_TYPES),
            "common layer keys: blend (" + ", ".join(BLEND_MODES) + "), opacity, mask (radial|linear|image), adjust ("
            + ", ".join(sorted(schema.ADJUST_KEYS)) + "), filters (" + ", ".join(schema.FILTER_KEYS) + "), visible",
            "text effects: " + ", ".join(sorted(schema.EFFECT_KEYS)),
            "image pre ops: " + ", ".join(schema.PRE_OPS),
            "export formats: " + ", ".join(schema.EXPORTS) + "  (ora = layered OpenRaster for GIMP/Krita)",
            "edit ops: crop, resize, rotate, flip, remove_background, trim_even, adjust, filter, vignette, overlay, text, border",
            "text: copy_id (needs the project's approved copy) or literal text with \"casual\": true"]
    return "\n".join(rows)


def _result(r: render.Rendered, paths: dict[str, Path] | None, prefix: str = "") -> list:
    lines = [prefix] if prefix else []
    lines.append(api.describe(r))
    if paths:
        lines += [f"{k}: {v}" for k, v in paths.items()]
    return ["\n".join(lines), _png(r.pil, 1000)]


@safe
def poster_preview(poster: dict | str, project: str = "", max_side: int = 720) -> list:
    """Render a small preview of a poster (JSON object or path to a .poster.json) and show it. Writes nothing.
    Same layout and text as the full render, just fewer pixels. Look at it, fix, then poster_render."""
    r, _ = on_gl(api.preview, poster, project, max_side)
    return _result(r, None, "preview (not saved)")


@safe
def poster_render(poster: dict | str, name: str = "", project: str = "", formats: list | None = None) -> list:
    """Render the poster at full size to <out>/posters/<name>.png (a project poster goes to the project's out/).
    Also writes <name>.poster.json (the reproducible sidecar) and <name>.text_audit.json (what text was drawn and that it
    equals its source). The poster's export list picks png/jpg/webp/ora/svg/pdf; ``formats`` overrides it
    (svg and pdf are vector files with text as outlines, sharp at any size)."""
    doc, base = api.load_poster(poster, project)
    bad = [f for f in formats or [] if f not in schema.EXPORTS]
    if bad:
        raise ValueError(f"unknown formats {bad}; have {list(schema.EXPORTS)}")

    def go():
        r = render.render_document(doc, base)
        return r, render.write_outputs(r, _out_dir(doc), name or r.doc.name, formats or None)
    r, paths = on_gl(go)
    return _result(r, paths)


@safe
def poster_variations(poster: dict | str, vary: dict, name: str = "var", project: str = "") -> list:
    """Render up to 12 variants of one poster and return a labelled contact sheet. vary = {key: [values]} with keys
    `seed`, `layers.<id>.<property...>`, `canvas.<k>`, `post.<n>.<k>`; several keys are zipped (same length).
    Files <name>-<i>.png (+ sidecar) and <name>-sheet.png land in <out>/posters/."""
    doc, base = api.load_poster(poster, project)
    res = on_gl(variations.poster_variations, doc, vary, _out_dir(doc), name, base)
    lines = [f"{len(res.files)} variants"] + [f"  {l}: {f['png']}" for l, f in zip(res.labels, res.files)]
    lines.append(f"sheet: {res.sheet}")
    return ["\n".join(lines), _png(res.sheet_image, 1400)]


@safe
def image_edit(path: str, ops: list, name: str = "", project: str = "", copy: str = "", casual: bool = False) -> list:
    """Edit a COPY of a picture; the original is never touched. ops run in order, geometry first (crop, resize, rotate,
    flip, remove_background, trim_even), then adjust {brightness, contrast, saturation, hue, ...}, filter {blur, sharpen,
    ...}, vignette, overlay {path, x, y, scale, blend, opacity}, text {copy_id|text, ...}, border {px, color}.
    Writes <out>/edits/<stem>-<name|n>.png, a sidecar that re-renders it, and a before/after sheet."""
    res = on_gl(editmod.edit_image, path, ops, name, project=project or None, copy=copy or None, casual=casual)
    lines = [f"{k}: {v}" for k, v in res.paths.items()] + [api.describe(res.rendered)]
    return ["\n".join(lines), _png(PILImage.open(res.compare), 1200)]


@safe
def poster_export_ora(poster: dict | str, name: str = "", project: str = "") -> list:
    """Render the poster and write it as a layered OpenRaster file (<name>.ora) that GIMP and Krita open with every layer,
    blend mode and opacity intact (layers are pre-rendered with their adjustments, filters, effects and masks;
    poster-level post passes are only in the PNG). Also writes the PNG."""
    doc, base = api.load_poster(poster, project)

    def go():
        r = render.render_document(doc, base)
        return r, render.write_outputs(r, _out_dir(doc), name or r.doc.name, ["png", "ora"])
    r, paths = on_gl(go)
    return _result(r, paths, api.ora_report(paths["ora"]))


@safe
def poster_compare(candidate: dict | str, reference: str, name: str = "compare", fit: str = "cover",
                   project: str = "") -> list:
    """How close is a render to a reference picture, and where does it differ? ``candidate`` is a picture path or a
    poster (JSON object or .poster.json, rendered first); ``reference`` is a picture path. Returns scores 0..100
    (overall, structure, colour, layout), the most different regions of a 4x4 grid, the reference's main colours with
    the nearest candidate colour, and a sheet: candidate | reference | heat map. ``fit``: cover (crop) or stretch.
    Writes <name>.compare.png and .compare.json to <out>/posters/. Use it to measure each fix, not to guess."""
    from funkbox.stills import compare as cmp
    if isinstance(candidate, dict) or str(candidate).endswith(".json"):
        doc, base = api.load_poster(candidate, project)
        cand = on_gl(lambda: render.render_document(doc, base)).pil
    else:
        cand = candidate
    res = cmp.compare(cand, reference, fit)
    paths = cmp.write(res, api.posters_dir(), name)
    return [res.summary() + "\n" + "\n".join(f"{k}: {v}" for k, v in paths.items()), _png(res.sheet, 1440)]


@safe
def poster_sizes(poster: dict | str, sizes: list, name: str = "", fit_to: str = "canvas", formats: list | None = None,
                 project: str = "") -> list:
    """One poster in many sizes. ``sizes``: preset names (story, landscape, square, insta-portrait, twitter, a4-150dpi)
    or {"name", "width", "height", "set": {"layers.<id>.<prop>": value}} with per-size fixes. Backgrounds stretch to
    the new canvas; text, shapes, SVGs and products keep their proportions (a layer's "resize": fill|fit|top|bottom|
    left|right|top-left|... chooses). fit_to="content" fits just the drawn foreground so wide or tall sizes use their
    space. Every size gets its own exact-text audit; one that cannot be drawn is reported and the rest still render.
    Writes <name>-<size>.png (+ formats such as svg/pdf) and <name>-sizes.png, a sheet."""
    from funkbox.stills import resize
    doc, base = api.load_poster(poster, project)
    res = on_gl(resize.poster_sizes, doc, sizes, _out_dir(doc), name, base, formats, 1.0, True, fit_to)
    lines = [f"{len(res.files)} of {len(res.names)} sizes rendered"]
    for k, files in res.files.items():
        exact = all(a["text_exact"] for a in res.audits.get(k, []))
        lines.append(f"  {k}: {files['png']}" + ("" if exact else "  (TEXT NOT EXACT - read the audit)"))
    lines += [f"  {k}: FAILED - {v}" for k, v in res.errors.items()] + res.notes
    if res.sheet:
        lines.append(f"sheet: {res.sheet}")
    return ["\n".join(lines)] + ([_png(res.sheet_image, 1400)] if res.sheet_image else [])


@safe
def image_trace(path: str, name: str = "", colors: int = 6, palette: list | None = None, detail: int = 1024,
                smooth: float = 1.0, tolerance: float = 0.8) -> list:
    """Trace a picture (logo, emblem, flat art) into a vector SVG of a few flat colours, sharp at any size; use it as
    an `svg` layer. ``palette`` (["#rrggbb", ...]) fixes the colours, else ``colors`` main colours are found.
    ``smooth`` 0 = straight segments, 1 = curves; ``tolerance`` (px) trades detail for fewer points; ``detail`` is the
    longest side traced. Reports a fidelity score (poster_compare of the trace against the original) and shows
    original | trace. Writes <out>/traces/<name>.svg and <name>.trace.png."""
    from funkbox.stills import trace as tr
    res = tr.trace(path, colors, palette, detail, smooth, tolerance)
    paths = tr.write(res, api.traces_dir(), name or Path(path).stem[:40].replace(" ", "-") or "trace")
    from funkbox.config import resolve_path
    orig = tr._over_white(PILImage.open(resolve_path(path)))
    side = PILImage.new("RGB", (orig.width * 2 + 8, orig.height), (24, 24, 28))
    side.paste(orig, (0, 0))
    side.paste(res.preview, (orig.width + 8, 0))
    lines = [f"{res.loops} shapes in {len(res.palette)} colours; fidelity {res.fidelity}/100",
             "colours: " + ", ".join(f"{p['color']} {p['share']:.0%}" for p in res.palette)]
    lines += [f"{k}: {v}" for k, v in paths.items()]
    return ["\n".join(lines), _png(side, 1400)]


@safe
def poster_animate(poster: dict | str, name: str = "", scale: float = 1.0, gif: bool = False,
                   seconds: float | None = None, fps: int | None = None, project: str = "") -> list:
    """Render a poster's ``motion`` block as a video: <name>.mp4 (+ .gif), the last frame as <name>.png (the poster
    itself: animations run towards the document's values), six frames on <name>-frames.png and
    <name>.motion_audit.json (every frame's text). motion = {seconds, fps, enter: [{layer, effect: fade|rise|drop|
    slide-left|slide-right|pop, at, dur}], tracks: {"layers.<id>.<prop>|dx|dy|scale": [[sec, value, ease?], ...]},
    loop_shaders}. ``scale`` 0.5 renders a quick draft."""
    from funkbox.stills import motion
    doc, base = api.load_poster(poster, project)
    res = on_gl(motion.animate, doc, _out_dir(doc), name, base, scale, gif, seconds, fps)
    lines = [f"{res.frames} frames, {res.seconds:g}s at {res.fps} fps; text exact in every frame: {res.all_exact}"]
    lines += [f"{k}: {v}" for k, v in res.paths.items()] + res.warnings
    return ["\n".join(lines), _png(res.sheet_image, 1600)]


TOOLS = [poster_presets, poster_preview, poster_render, poster_variations, poster_export_ora, poster_compare,
         poster_sizes, poster_animate, image_edit, image_trace]


def register(server) -> None:
    for fn in TOOLS:
        server.tool(name=fn.__name__)(fn)
