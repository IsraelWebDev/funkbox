"""v3.1 "projects": the folder layout, project.json and the copy lock.

    projects/<slug>/
      project.json        name, created, status, brand, copy_lock (sha256 of copy.json), notes
      product/  brand/  shots/  clips/  music/
      copy.draft.json     proposals (the agent may write this)
      copy.json           APPROVED copy (written ONLY by approval.approve; see approval.py)
      <slug>.reel.json    generated by auto_reel, editable
      out/                renders for this project

The exactness guarantee lives here too: ``copy_lock_error`` / ``check_reel_copy`` are called by the
v3 validator, so a reel inside a project can only ever use the project's *approved* ``copy.json`` and
only while its sha256 still equals ``project.json.copy_lock``.
"""
from __future__ import annotations

import datetime as _dt
import hashlib
import json
import os
import re
import tempfile
from pathlib import Path
from typing import Any

from funkgl.recipe import funk_home, funk_projects

SLUG_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,40}$")
SUBDIRS = ("product", "brand", "brand/fonts", "shots", "clips", "music", "out")
LOCK_MSG = "copy.json changed since approval; run propose_copy/approve_copy again."
UNAPPROVED_MSG = "copy.json has not been approved; run propose_copy, show the listing to the user, then approve_copy."

STATUSES = ("new", "ingested", "branded", "copy-drafted", "copy-approved", "reel-built", "rendered")


class ProjectError(ValueError):
    pass


def projects_root() -> Path:
    return funk_projects()


def inbox_dir() -> Path:
    """Where the user drops files (env FUNK_INBOX, default <FUNK_HOME>/inbox). Created on first use."""
    return Path(os.environ.get("FUNK_INBOX") or (funk_home() / "inbox")).expanduser().resolve()


def ensure_inbox() -> Path:
    d = inbox_dir()
    d.mkdir(parents=True, exist_ok=True)
    return d


def now_iso() -> str:
    return _dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def sha256_bytes(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def sha256_file(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def slugify(name: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", (name or "").lower()).strip("-")
    return s[:41].strip("-")


def project_dir(slug: str, must_exist: bool = True) -> Path:
    if not isinstance(slug, str) or not SLUG_RE.match(slug):
        raise ProjectError(f"bad project name {slug!r}: use a slug matching {SLUG_RE.pattern} "
                           f"(lowercase letters, digits and dashes)")
    d = projects_root() / slug
    if must_exist and not (d / "project.json").is_file():
        have = ", ".join(list_slugs()) or "none yet"
        raise ProjectError(f"no project {slug!r} (projects: {have}); create it with new_project")
    return d


def list_slugs() -> list[str]:
    root = projects_root()
    if not root.is_dir():
        return []
    return sorted(p.name for p in root.iterdir() if SLUG_RE.match(p.name) and (p / "project.json").is_file())


# --------------------------------------------------------------------------- #
# project.json
# --------------------------------------------------------------------------- #
def _write_json_atomic(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=path.name + ".", suffix=".part", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(json.dumps(data, indent=2, ensure_ascii=False) + "\n")
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


def load_meta(slug: str) -> dict:
    d = project_dir(slug)
    return json.loads((d / "project.json").read_text(encoding="utf-8"))


def save_meta(slug: str, meta: dict) -> None:
    _write_json_atomic(project_dir(slug) / "project.json", meta)


def update_meta(slug: str, **changes: Any) -> dict:
    meta = load_meta(slug)
    meta.update(changes)
    save_meta(slug, meta)
    return meta


def advance_status(slug: str, status: str) -> None:
    """Move status forward only (never back), so a late tool call cannot hide progress."""
    meta = load_meta(slug)
    if STATUSES.index(status) > STATUSES.index(meta.get("status", "new")):
        meta["status"] = status
        save_meta(slug, meta)


def new_project(name: str) -> dict:
    slug = slugify(name)
    if not slug or not SLUG_RE.match(slug):
        raise ProjectError(f"cannot make a project name from {name!r}; use letters and digits")
    d = projects_root() / slug
    if (d / "project.json").exists():
        raise ProjectError(f"project {slug!r} already exists; use it, or pick another name")
    for sub in SUBDIRS:
        (d / sub).mkdir(parents=True, exist_ok=True)
    meta = {"name": name.strip(), "slug": slug, "created": now_iso(), "status": "new", "brand": None,
            "copy_lock": None, "copy_approval": None, "product": None, "assets": {}, "notes": []}
    _write_json_atomic(d / "project.json", meta)
    ensure_inbox()
    return meta


def list_projects() -> list[dict]:
    out = []
    for slug in list_slugs():
        m = load_meta(slug)
        d = project_dir(slug)
        out.append({"slug": slug, "name": m.get("name", slug), "status": m.get("status", "new"),
                    "created": m.get("created"), "has_product": (d / "product" / "product.png").exists(),
                    "copy_approved": bool(m.get("copy_lock")),
                    "shots": len(files_in(d / "shots")), "clips": len(files_in(d / "clips")),
                    "music": len(files_in(d / "music"))})
    return out


def files_in(d: Path) -> list[Path]:
    if not d.is_dir():
        return []
    return sorted(p for p in d.iterdir() if p.is_file() and not p.name.startswith("."))


# --------------------------------------------------------------------------- #
# The copy lock
# --------------------------------------------------------------------------- #
def copy_lock_error(slug: str, data: bytes | None = None) -> str | None:
    """None when copy.json exists and sha256(copy.json) == project.json.copy_lock; else the message.
    ``data`` (the bytes the caller already read) is hashed instead of re-reading the file."""
    d = project_dir(slug)
    cp = d / "copy.json"
    if cp.is_symlink() or not cp.is_file():
        return f"project {slug!r} has no approved copy.json; run propose_copy, then approve_copy."
    meta = load_meta(slug)
    lock = meta.get("copy_lock")
    if not lock:
        return UNAPPROVED_MSG
    if (sha256_bytes(data) if data is not None else sha256_file(cp)) != lock:
        return LOCK_MSG
    return None


def _inside(path: Path, root: Path) -> Path | None:
    """The path relative to root when path is inside it, else None."""
    try:
        return path.resolve().relative_to(root.resolve())
    except (ValueError, OSError):
        return None


def check_reel_copy(copy_path: Path, base_dir: str | Path | None, data: bytes | None = None) -> str | None:
    """Validator hook. Rules (the exactness guarantee for projects):

    * a copy deck inside ``projects/<slug>/`` must be exactly that project's ``copy.json``
      (so ``copy.draft.json`` can never reach pixels or audio) and must match the lock;
    * a reel file stored inside ``projects/<slug>/`` must use that same ``copy.json``.
    """
    root = projects_root()
    rel = _inside(copy_path, root)
    base_rel = _inside(Path(base_dir), root) if base_dir else None
    slug = None
    if rel is not None and rel.parts:
        slug = rel.parts[0]
    elif base_rel is not None and base_rel.parts:
        slug = base_rel.parts[0]
        return (f"reel is stored in project {slug!r} but its copy deck {copy_path} is not that project's "
                f"copy.json; project reels may only use the approved copy.json")
    if slug is None:
        return None
    if base_rel is not None and base_rel.parts and base_rel.parts[0] != slug:
        return f"reel is stored in project {base_rel.parts[0]!r} but uses the copy deck of project {slug!r}"
    if not SLUG_RE.match(slug) or not (root / slug / "project.json").is_file():
        return f"copy deck {copy_path} is inside the projects folder but not in a project"
    if rel is None or tuple(rel.parts) != (slug, "copy.json"):
        return (f"inside project {slug!r} only the approved copy.json may be used as the copy deck "
                f"(got {'/'.join(rel.parts[1:]) if rel else copy_path}); copy.draft.json never reaches pixels")
    return copy_lock_error(slug, data)
