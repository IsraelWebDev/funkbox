#!/usr/bin/env python3
"""
funk v3.2 "stills" as an MCP server: layered posters and photo edits, rendered on the GPU, with exact text.

Register (Claude Code):
    claude mcp add stills -e FUNK_OUT=C:\\dev\\funkbox\\out -- C:\\dev\\funkbox\\.venv\\Scripts\\python.exe C:\\dev\\funkbox\\stills_mcp.py
Env: FUNK_OUT, FUNK_INPUTS, FUNK_HOME, FUNK_GL_BACKEND (egl|default).

NOTHING may be printed to stdout here: stdout is the MCP protocol. Logs go to stderr.
Text on a poster is drawn by this server from the copy deck by ID (projects) or from a literal marked "casual";
it is never generated by an image model, and every render writes a text audit proving what was drawn.
"""
from __future__ import annotations

import functools
import io
import json
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import Any, Callable

from PIL import Image as PILImage

try:  # mcp >= 2
    from mcp.server.mcpserver import Image, MCPServer as _Server
except ImportError:  # mcp 1.x
    from mcp.server.fastmcp import FastMCP as _Server, Image  # type: ignore

sys.path.insert(0, str(Path(__file__).resolve().parent))

from funkbox.gl.context import GLUnavailable  # noqa: E402
from funkbox.config import funk_inputs, funk_out  # noqa: E402
from funkbox.stills import api, edit as editmod, ora, render, schema, variations  # noqa: E402

INSTRUCTIONS = (
    "Always preview_poster (or poster_variations) before a full render_poster, and look at the picture. "
    "In a project, text layers use copy_id from the approved copy and never literal text; literal text is allowed only "
    "in a poster marked casual, and the product photo is composited, never generated. "
    "After the user picks a design, offer export_ora so they can keep editing the layers in GIMP."
)

server = _Server("stills", instructions=INSTRUCTIONS)


def _log(*a) -> None:
    print(*a, file=sys.stderr)


_GL = ThreadPoolExecutor(max_workers=1, thread_name_prefix="stills-gl")


def on_gl(fn: Callable, *a, **k):
    """GL contexts are thread-affine: every tool body runs on ONE dedicated thread."""
    return _GL.submit(lambda: fn(*a, **k)).result()


def _png(img: PILImage.Image, max_side: int = 900) -> Image:
    img = img.copy()
    if img.mode == "RGBA":
        img = editmod.checker_flatten(img)
    img.thumbnail((max_side, max_side))
    buf = io.BytesIO()
    img.save(buf, format="PNG", optimize=True)
    return Image(data=buf.getvalue(), format="png")


def _safe(fn):
    @functools.wraps(fn)
    def wrapper(*a, **k):
        try:
            return fn(*a, **k)
        except GLUnavailable as e:
            return f"ERROR: no OpenGL context available. {e}"
        except schema.PosterError as e:
            return "ERROR: " + "\n".join(e.errors)
        except (ValueError, KeyError, TypeError, FileNotFoundError, RuntimeError, OSError) as e:
            return f"ERROR: {type(e).__name__}: {e}"
        except Exception as e:  # noqa: BLE001
            _log(f"stills_mcp: unexpected {type(e).__name__}: {e}")
            return f"ERROR: unexpected {type(e).__name__}: {e}"
    return wrapper


def _out_dir(doc: dict) -> Path:
    if doc.get("project"):
        from funkbox.reel import project as projmod
        return projmod.project_dir(doc["project"]) / "out"
    return api.posters_dir()


# --------------------------------------------------------------------------- #
@server.tool()
@_safe
def presets() -> str:
    """Canvas presets, layer types, blend modes, filters, effects, export formats and the edit operations."""
    from funkbox.gl.recipe import BLEND_MODES
    rows = ["canvas presets: " + ", ".join(f"{k} {w}x{h}" for k, (w, h) in schema.PRESETS.items())
            + f"  (or width/height, {schema.MIN_SIDE}..{schema.MAX_SIDE}; background may be \"transparent\")",
            "layer types: " + ", ".join(schema.LAYER_TYPES),
            "common layer keys: blend (" + ", ".join(BLEND_MODES) + "), opacity, mask (radial|linear|image), adjust ("
            + ", ".join(sorted(schema.ADJUST_KEYS)) + "), filters (" + ", ".join(schema.FILTER_KEYS) + "), visible",
            "text effects: " + ", ".join(sorted(schema.EFFECT_KEYS)),
            "image pre ops: " + ", ".join(schema.PRE_OPS),
            "export formats: " + ", ".join(schema.EXPORTS) + "  (ora = layered OpenRaster for GIMP/Krita)",
            "edit ops: crop, resize, rotate, flip, remove_background, trim_even, adjust, filter, vignette, overlay, text, border",
            "text: copy_id (needs the project's approved copy) or literal text with \"casual\": true"]
    return "\n".join(rows)


def _result(r: render.Rendered, paths: dict[str, Path] | None, prefix: str = "") -> list:
    lines = [prefix] if prefix else []
    lines.append(api.describe(r))
    if paths:
        lines += [f"{k}: {v}" for k, v in paths.items()]
    return ["\n".join(lines), _png(r.pil, 1000)]


@server.tool()
@_safe
def preview_poster(poster: dict | str, project: str = "", max_side: int = 720) -> list:
    """Render a small preview of a poster (JSON object or path to a .poster.json) and show it. Writes nothing.
    Same layout and text as the full render, just fewer pixels. Look at it, fix, then render_poster."""
    r, _ = on_gl(api.preview, poster, project, max_side)
    return _result(r, None, "preview (not saved)")


@server.tool(name="render_poster")
@_safe
def render_poster_tool(poster: dict | str, name: str = "", project: str = "") -> list:
    """Render the poster at full size to <out>/posters/<name>.png (a project poster goes to the project's out/).
    Also writes <name>.poster.json (the reproducible sidecar) and <name>.text_audit.json (what text was drawn and that it
    equals its source). The poster's export list picks png/jpg/webp/ora."""
    doc, base = api.load_poster(poster, project)

    def go():
        r = render.render_document(doc, base)
        return r, render.write_outputs(r, _out_dir(doc), name or r.doc.name)
    r, paths = on_gl(go)
    return _result(r, paths)


@server.tool()
@_safe
def poster_variations(poster: dict | str, vary: dict, name: str = "var", project: str = "") -> list:
    """Render up to 12 variants of one poster and return a labelled contact sheet. vary = {key: [values]} with keys
    `seed`, `layers.<id>.<property...>`, `canvas.<k>`, `post.<n>.<k>`; several keys are zipped (same length).
    Files <name>-<i>.png (+ sidecar) and <name>-sheet.png land in <out>/posters/."""
    doc, base = api.load_poster(poster, project)
    res = on_gl(variations.poster_variations, doc, vary, _out_dir(doc), name, base)
    lines = [f"{len(res.files)} variants"] + [f"  {l}: {f['png']}" for l, f in zip(res.labels, res.files)]
    lines.append(f"sheet: {res.sheet}")
    return ["\n".join(lines), _png(res.sheet_image, 1400)]


@server.tool()
@_safe
def edit_image(path: str, ops: list, name: str = "", project: str = "", copy: str = "", casual: bool = False) -> list:
    """Edit a COPY of a picture; the original is never touched. ops run in order, geometry first (crop, resize, rotate,
    flip, remove_background, trim_even), then adjust {brightness, contrast, saturation, hue, ...}, filter {blur, sharpen,
    ...}, vignette, overlay {path, x, y, scale, blend, opacity}, text {copy_id|text, ...}, border {px, color}.
    Writes <out>/edits/<stem>-<name|n>.png, a sidecar that re-renders it, and a before/after sheet."""
    res = on_gl(editmod.edit_image, path, ops, name, project=project or None, copy=copy or None, casual=casual)
    lines = [f"{k}: {v}" for k, v in res.paths.items()] + [api.describe(res.rendered)]
    return ["\n".join(lines), _png(PILImage.open(res.compare), 1200)]


@server.tool()
@_safe
def funk_still(recipe_or_shader: str | dict, t: float = 0.25, preset: str = "square", name: str = "") -> list:
    """One frame of a funk2 recipe (JSON object or .json path) or a shader (.frag path or GLSL source with
    `vec4 effect(vec2 p)`) at time t (0..1 of the loop), as a PNG poster background in <out>/stills/."""
    paths, r = on_gl(api.funk_still, recipe_or_shader, t, preset, name)
    return _result(r, paths)


@server.tool()
@_safe
def export_ora(poster: dict | str, name: str = "", project: str = "") -> list:
    """Render the poster and write it as a layered OpenRaster file (<name>.ora) that GIMP and Krita open with every layer,
    blend mode and opacity intact (layers are pre-rendered with their adjustments, filters, effects and masks;
    poster-level post passes are only in the PNG). Also writes the PNG."""
    doc, base = api.load_poster(poster, project)

    def go():
        r = render.render_document(doc, base)
        return r, render.write_outputs(r, _out_dir(doc), name or r.doc.name, ["png", "ora"])
    r, paths = on_gl(go)
    return _result(r, paths, api.ora_report(paths["ora"]))


def main() -> None:
    funk_inputs().mkdir(parents=True, exist_ok=True)
    funk_out().mkdir(parents=True, exist_ok=True)
    server.run()


if __name__ == "__main__":
    main()
